# ----------------------------------------------------------------------------- CSS: scope every rule under #atlas
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
DROP = re.compile(r'^(:root|html|body|header\.top|\.top-in|\.brand|main)(\b|$|[\s:.\[{,])')


def blocks(text):
    i, out = 0, []
    while True:
        j = text.find('{', i)
        if j < 0: break
        depth, k = 1, j + 1
        while depth:
            if text[k] == '{': depth += 1
            elif text[k] == '}': depth -= 1
            k += 1
        out.append((text[i:j].strip(), text[j + 1:k - 1]))
        i = k
    return out


def scope(text):
    out = []
    for prelude, body in blocks(text):
        if prelude.startswith('@media'):
            inner = scope(body)
            if inner.strip(): out.append(f'{prelude}{{{inner}}}')
            continue
        sels = [s.strip() for s in prelude.split(',')]
        if any(DROP.match(s) for s in sels): continue
        out.append(','.join('#atlas ' + s for s in sels) + '{' + body.strip() + '}')
    return '\n'.join(out)


